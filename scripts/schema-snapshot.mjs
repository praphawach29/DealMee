#!/usr/bin/env node
/**
 * The live database's structure, kept in git, and a check that new migrations only touch
 * columns that exist there.
 *
 * Why: the migrations in this repo don't describe production. Tables were edited by hand
 * over time (products has sku/price_used/workspace_id, shops has slug/package_name/status,
 * and promptpay_id or products.status never existed), so a migration written from the files
 * can fail on the real database — the live-demo migration failed twice on 24 Oct 2026.
 *
 *   node scripts/schema-snapshot.mjs import <file>   save a dump (CSV or JSON from the SQL Editor)
 *   node scripts/schema-snapshot.mjs check [files…]   check migrations against the snapshot
 *
 * `import` writes supabase/schema/production.json (full) and production.md (one table per
 * section, for reading). `check` with no files checks the migrations this branch adds or
 * changes compared with origin/main.
 * `check` also scans src/ for supabase-js chains that name a table or column production
 * doesn't have. Exit code 1 on any problem.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { execSync } from 'node:child_process'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SCHEMA_DIR = join(ROOT, 'supabase', 'schema')
const SNAPSHOT_JSON = join(SCHEMA_DIR, 'production.json')
const SNAPSHOT_MD = join(SCHEMA_DIR, 'production.md')

// ─── import ───────────────────────────────────────────────────────────────────

/** The SQL Editor gives either the bare JSON, a CSV with one column, or "Copy as JSON" rows. */
function extractSchemaJson(raw) {
  const text = raw.replace(/^\uFEFF/, '').trim()
  if (text.startsWith('{')) return JSON.parse(text)
  if (text.startsWith('[')) {
    const rows = JSON.parse(text)
    const cell = rows?.[0]?.schema_json
    if (!cell) throw new Error('JSON rows have no schema_json column')
    return typeof cell === 'string' ? JSON.parse(cell) : cell
  }
  // CSV: header line, then one quoted cell where quotes are doubled
  const firstNewline = text.indexOf('\n')
  const header = text.slice(0, firstNewline).trim().replace(/"/g, '')
  if (header !== 'schema_json') throw new Error(`Unexpected CSV header "${header}" (expected schema_json)`)
  let cell = text.slice(firstNewline + 1).trim()
  if (cell.startsWith('"') && cell.endsWith('"')) cell = cell.slice(1, -1).replace(/""/g, '"')
  return JSON.parse(cell)
}

function renderMarkdown(schema) {
  const out = []
  out.push('# Production database structure')
  out.push('')
  out.push(`Captured ${schema.captured_at} · Postgres ${schema.postgres}`)
  out.push('')
  out.push('Generated by `node scripts/schema-snapshot.mjs import` from `dump-schema.sql`. Do not edit by hand —')
  out.push('this is what the live database has, which is not always what supabase/migrations says.')
  out.push('')
  out.push(`${schema.tables.length} tables · ${schema.functions.length} functions · ${schema.views.length} views`)
  out.push('')
  for (const t of schema.tables) {
    const flags = [t.rls ? 'RLS on' : '⚠️ RLS OFF', `${t.policies.length} policies`]
    const grants = Object.entries(t.grants || {})
      .filter(([role]) => role !== 'service_role')
      .map(([role, privs]) => `${role}: ${privs}`)
    if (grants.length) flags.push(grants.join(' · '))
    out.push(`## ${t.name}`)
    out.push('')
    out.push(flags.join(' · '))
    out.push('')
    out.push('| column | type | null | default |')
    out.push('|---|---|---|---|')
    for (const c of t.columns) {
      out.push(`| ${c.name} | ${c.type} | ${c.nullable ? 'yes' : 'no'} | ${c.default ? `\`${String(c.default).replace(/\|/g, '\\|')}\`` : ''} |`)
    }
    out.push('')
  }
  out.push('## Functions')
  out.push('')
  for (const f of schema.functions) {
    out.push(`- \`${f.name}(${f.args})\` → ${f.returns}${f.security_definer ? ' · security definer' : ''}`)
  }
  out.push('')
  out.push('## Extensions')
  out.push('')
  out.push(schema.extensions.map((e) => `${e.name} ${e.version}`).join(' · '))
  out.push('')
  return out.join('\n')
}

function importDump(file) {
  const schema = extractSchemaJson(readFileSync(file, 'utf8'))
  if (!Array.isArray(schema.tables)) throw new Error('Dump has no tables — was it run on the right project?')
  writeFileSync(SNAPSHOT_JSON, JSON.stringify(schema, null, 2) + '\n')
  writeFileSync(SNAPSHOT_MD, renderMarkdown(schema))
  console.log(`Saved ${schema.tables.length} tables, ${schema.functions.length} functions (captured ${schema.captured_at})`)
}

// ─── check ────────────────────────────────────────────────────────────────────

const IDENT = '(?:"[^"]+"|[a-zA-Z_][a-zA-Z0-9_]*)'
const unquote = (s) => s.replace(/^"|"$/g, '')
const stripComments = (sql) => sql.replace(/--[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '')

/** Columns a migration file writes by name, per table: insert column lists and update set lists */
function referencedColumns(sql) {
  const refs = []
  const insertRe = new RegExp(`insert\\s+into\\s+(?:public\\.)?(${IDENT})\\s*\\(([^)]*)\\)`, 'gi')
  for (const m of sql.matchAll(insertRe)) {
    for (const col of m[2].split(',')) refs.push({ table: unquote(m[1]), column: unquote(col.trim()), how: 'insert' })
  }
  const updateRe = new RegExp(`update\\s+(?:public\\.)?(${IDENT})\\s+set\\s+([\\s\\S]*?)(?:\\bwhere\\b|\\bfrom\\b|\\breturning\\b|;)`, 'gi')
  for (const m of sql.matchAll(updateRe)) {
    // top-level "col = ..." pairs; nested parentheses are skipped
    let depth = 0
    let part = ''
    const parts = []
    for (const ch of m[2]) {
      if (ch === '(') depth++
      if (ch === ')') depth--
      if (ch === ',' && depth === 0) { parts.push(part); part = '' } else part += ch
    }
    parts.push(part)
    for (const p of parts) {
      const col = p.split('=')[0]?.trim()
      if (col && new RegExp(`^${IDENT}$`).test(col)) refs.push({ table: unquote(m[1]), column: unquote(col), how: 'update' })
    }
  }
  return refs
}

/** Tables and columns the same file creates, so referencing them isn't a mistake */
function createdInFile(sql) {
  const tables = new Set()
  const columns = new Set()
  const createRe = new RegExp(`create\\s+table\\s+(?:if\\s+not\\s+exists\\s+)?(?:public\\.)?(${IDENT})`, 'gi')
  for (const m of sql.matchAll(createRe)) tables.add(unquote(m[1]))
  const addRe = new RegExp(`alter\\s+table\\s+(?:if\\s+exists\\s+)?(?:only\\s+)?(?:public\\.)?(${IDENT})([\\s\\S]*?);`, 'gi')
  for (const m of sql.matchAll(addRe)) {
    const colRe = new RegExp(`add\\s+column\\s+(?:if\\s+not\\s+exists\\s+)?(${IDENT})`, 'gi')
    for (const c of m[2].matchAll(colRe)) columns.add(`${unquote(m[1])}.${unquote(c[1])}`)
  }
  return { tables, columns }
}

function changedMigrations() {
  const run = (cmd) => {
    try {
      return execSync(cmd, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).split('\n').filter(Boolean)
    } catch {
      return []
    }
  }
  const names = new Set([
    ...run('git diff --name-only origin/main...HEAD -- supabase/migrations'),
    ...run('git diff --name-only HEAD -- supabase/migrations'),
    ...run('git ls-files --others --exclude-standard -- supabase/migrations'),
  ])
  return [...names].filter((f) => f.endsWith('.sql') && existsSync(join(ROOT, f))).map((f) => join(ROOT, f))
}

function check(files) {
  const schema = JSON.parse(readFileSync(SNAPSHOT_JSON, 'utf8'))
  const live = new Map(schema.tables.map((t) => [t.name, new Set(t.columns.map((c) => c.name))]))

  if (files.length === 0) {
    // The migrations this branch adds or changes. File names here are not real dates (some
    // are dated ahead of when they ran), so they can't tell what production has already seen.
    files = changedMigrations()
  }
  let problems = checkCode(live)
  if (files.length === 0) {
    console.log('No new or changed migrations on this branch (compared with origin/main).')
  }

  for (const file of files) {
    const sql = stripComments(readFileSync(file, 'utf8'))
    const made = createdInFile(sql)
    for (const ref of referencedColumns(sql)) {
      if (made.tables.has(ref.table) || made.columns.has(`${ref.table}.${ref.column}`)) continue
      const cols = live.get(ref.table)
      if (!cols) {
        console.log(`✗ ${basename(file)}: table "${ref.table}" is not in production (${ref.how})`)
        problems++
      } else if (!cols.has(ref.column)) {
        console.log(`✗ ${basename(file)}: column "${ref.table}.${ref.column}" is not in production (${ref.how})`)
        problems++
      }
    }
  }
  console.log(problems ? `\n${problems} problem(s). See supabase/schema/production.md for what each table has.` : `✓ src/ and ${files.length} migration(s) only use columns production has.`)
  return problems ? 1 : 0
}


// ─── code check ───────────────────────────────────────────────────────────────

/**
 * Columns the app names in supabase-js chains: .from('t').select('a, b') and filters like
 * .eq('col', …). A heuristic (one chain, up to the next ';' or .from), but it is what found
 * orders.payment_status, broadcasts.recipient_count and the copilot's wrong column names.
 */
function checkCode(live) {
  const files = []
  const walk = (dir) => {
    for (const name of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, name.name)
      if (name.isDirectory()) walk(full)
      else if (/\.(ts|tsx)$/.test(name.name)) files.push(full)
    }
  }
  walk(join(ROOT, 'src'))
  let problems = 0
  for (const file of files) {
    const code = readFileSync(file, 'utf8')
    for (const m of code.matchAll(/\.from\(\s*'([a-z_]+)'\s*\)/g)) {
      const table = m[1]
      const cols = live.get(table)
      const rel = file.slice(ROOT.length + 1)
      if (!cols) {
        console.log(`✗ ${rel}: table "${table}" is not in production`)
        problems++
        continue
      }
      let chain = code.slice(m.index + m[0].length, m.index + m[0].length + 1500)
      const stops = [chain.indexOf(';'), chain.indexOf('.from(')].filter((i) => i >= 0)
      if (stops.length) chain = chain.slice(0, Math.min(...stops))
      const named = new Set()
      for (const sel of chain.matchAll(/\.select\(\s*'([^']*)'/g)) {
        for (const part of sel[1].split(',')) {
          const p = part.trim()
          if (!p || p === '*' || /[(:!.]/.test(p)) continue
          named.add(p.split(/\s/)[0])
        }
      }
      for (const f of chain.matchAll(/\.(?:eq|neq|in|gt|gte|lt|lte|is|not|ilike|like|order|contains)\(\s*'([a-z_]+)'/g)) named.add(f[1])
      for (const col of named) {
        if (!cols.has(col)) {
          console.log(`✗ ${rel}: column "${table}.${col}" is not in production`)
          problems++
        }
      }
    }
  }
  return problems
}

// ─── main ─────────────────────────────────────────────────────────────────────

const [cmd, ...args] = process.argv.slice(2)
try {
  if (cmd === 'import' && args[0]) importDump(args[0])
  else if (cmd === 'check') process.exit(check(args))
  else {
    console.log('Usage:\n  node scripts/schema-snapshot.mjs import <dump.csv|json>\n  node scripts/schema-snapshot.mjs check [migration.sql…]')
    process.exit(2)
  }
} catch (err) {
  console.error(err instanceof Error ? err.message : err)
  process.exit(1)
}
